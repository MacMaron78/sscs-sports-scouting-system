CREATE TABLE IF NOT EXISTS sscs_api.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(30) NOT NULL,
    email VARCHAR(254) NOT NULL,
    password_hash TEXT NOT NULL,
    role VARCHAR(10) NOT NULL CHECK (role IN ('athlete', 'scout', 'admin')),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    token_version INTEGER NOT NULL DEFAULT 0,
    verification_status VARCHAR(16) NOT NULL DEFAULT 'unverified'
        CHECK (verification_status IN ('unverified', 'pending', 'verified', 'rejected')),
    verification_requested_at TIMESTAMPTZ,
    verification_reviewed_at TIMESTAMPTZ,
    verification_reviewed_by BIGINT REFERENCES sscs_api.users(id) ON DELETE SET NULL,
    profile_photo BYTEA,
    profile_photo_type VARCHAR(32),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE sscs_api.users ADD COLUMN IF NOT EXISTS token_version INTEGER NOT NULL DEFAULT 0;
ALTER TABLE sscs_api.users ADD COLUMN IF NOT EXISTS verification_status VARCHAR(16) NOT NULL DEFAULT 'unverified'
    CHECK (verification_status IN ('unverified', 'pending', 'verified', 'rejected'));
ALTER TABLE sscs_api.users ADD COLUMN IF NOT EXISTS verification_requested_at TIMESTAMPTZ;
ALTER TABLE sscs_api.users ADD COLUMN IF NOT EXISTS verification_reviewed_at TIMESTAMPTZ;
ALTER TABLE sscs_api.users ADD COLUMN IF NOT EXISTS verification_reviewed_by BIGINT
    REFERENCES sscs_api.users(id) ON DELETE SET NULL;
ALTER TABLE sscs_api.users ADD COLUMN IF NOT EXISTS profile_photo BYTEA;
ALTER TABLE sscs_api.users ADD COLUMN IF NOT EXISTS profile_photo_type VARCHAR(32);

CREATE UNIQUE INDEX IF NOT EXISTS sscs_api_users_username_lower_unique
    ON sscs_api.users (LOWER(username));
CREATE UNIQUE INDEX IF NOT EXISTS sscs_api_users_email_lower_unique
    ON sscs_api.users (LOWER(email));

CREATE TABLE IF NOT EXISTS sscs_api.password_reset_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES sscs_api.users(id) ON DELETE CASCADE,
    status VARCHAR(16) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'approved', 'declined', 'completed', 'superseded')),
    requested_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    reviewed_at TIMESTAMPTZ,
    reviewed_by BIGINT REFERENCES sscs_api.users(id) ON DELETE SET NULL,
    reset_code_hash TEXT,
    reset_code_expires_at TIMESTAMPTZ,
    failed_attempts INTEGER NOT NULL DEFAULT 0 CHECK (failed_attempts >= 0),
    completed_at TIMESTAMPTZ
);

ALTER TABLE sscs_api.password_reset_requests
    ADD COLUMN IF NOT EXISTS failed_attempts INTEGER NOT NULL DEFAULT 0;

CREATE UNIQUE INDEX IF NOT EXISTS sscs_api_password_reset_pending_user_unique
    ON sscs_api.password_reset_requests (user_id)
    WHERE status = 'pending';
CREATE INDEX IF NOT EXISTS sscs_api_password_reset_queue_idx
    ON sscs_api.password_reset_requests (status, requested_at DESC);

CREATE TABLE IF NOT EXISTS sscs_api.password_reset_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reset_request_id BIGINT REFERENCES sscs_api.password_reset_requests(id) ON DELETE SET NULL,
    user_id BIGINT REFERENCES sscs_api.users(id) ON DELETE SET NULL,
    actor_id BIGINT REFERENCES sscs_api.users(id) ON DELETE SET NULL,
    event_type VARCHAR(32) NOT NULL
        CHECK (event_type IN ('requested', 'approved', 'declined', 'code_regenerated', 'code_attempt_failed', 'code_locked', 'reset_completed')),
    details JSONB NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(details) = 'object'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS sscs_api_password_reset_audit_created_idx
    ON sscs_api.password_reset_audit (created_at DESC);

CREATE TABLE IF NOT EXISTS sscs_api.athlete_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES sscs_api.users(id) ON DELETE CASCADE,
    first_name VARCHAR(150) NOT NULL,
    last_name VARCHAR(150) NOT NULL,
    sport VARCHAR(100) NOT NULL,
    position VARCHAR(100) NOT NULL,
    age SMALLINT CHECK (age IS NULL OR age BETWEEN 0 AND 125),
    location VARCHAR(255) NOT NULL,
    competition_level VARCHAR(50) NOT NULL DEFAULT '',
    is_discoverable BOOLEAN NOT NULL DEFAULT TRUE,
    bio TEXT NOT NULL DEFAULT '',
    video_link TEXT NOT NULL DEFAULT '',
    career_history JSONB NOT NULL DEFAULT '[]'::jsonb
        CHECK (jsonb_typeof(career_history) = 'array'),
    performance_stats JSONB NOT NULL DEFAULT '{}'::jsonb
        CHECK (jsonb_typeof(performance_stats) = 'object'),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE sscs_api.athlete_profiles ADD COLUMN IF NOT EXISTS is_discoverable BOOLEAN NOT NULL DEFAULT TRUE;
ALTER TABLE sscs_api.athlete_profiles ADD COLUMN IF NOT EXISTS competition_level VARCHAR(50) NOT NULL DEFAULT '';

CREATE INDEX IF NOT EXISTS sscs_api_athlete_search_idx
    ON sscs_api.athlete_profiles (
        LOWER(sport),
        LOWER(position),
        age,
        LOWER(location),
        LOWER(competition_level)
    );

CREATE TABLE IF NOT EXISTS sscs_api.agency_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES sscs_api.users(id) ON DELETE CASCADE,
    agency_name VARCHAR(255) NOT NULL,
    country VARCHAR(100) NOT NULL,
    contact_phone VARCHAR(32) NOT NULL DEFAULT '',
    contact_details TEXT NOT NULL DEFAULT '',
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS sscs_api.shortlists (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agency_id BIGINT NOT NULL REFERENCES sscs_api.agency_profiles(id) ON DELETE CASCADE,
    athlete_id BIGINT NOT NULL REFERENCES sscs_api.athlete_profiles(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT sscs_api_shortlist_agency_athlete_unique UNIQUE (agency_id, athlete_id)
);

CREATE TABLE IF NOT EXISTS sscs_api.messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_id BIGINT NOT NULL REFERENCES sscs_api.users(id) ON DELETE CASCADE,
    recipient_id BIGINT NOT NULL REFERENCES sscs_api.users(id) ON DELETE CASCADE,
    body TEXT NOT NULL CHECK (LENGTH(BTRIM(body)) > 0),
    sent_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    is_read BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE INDEX IF NOT EXISTS sscs_api_messages_inbox_idx
    ON sscs_api.messages (recipient_id, sent_at DESC);
CREATE INDEX IF NOT EXISTS sscs_api_messages_sent_idx
    ON sscs_api.messages (sender_id, sent_at DESC);

CREATE TABLE IF NOT EXISTS sscs_api.user_blocks (
    blocker_id BIGINT NOT NULL REFERENCES sscs_api.users(id) ON DELETE CASCADE,
    blocked_id BIGINT NOT NULL REFERENCES sscs_api.users(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (blocker_id, blocked_id),
    CHECK (blocker_id <> blocked_id)
);

CREATE INDEX IF NOT EXISTS sscs_api_user_blocks_blocked_idx
    ON sscs_api.user_blocks (blocked_id, blocker_id);

CREATE TABLE IF NOT EXISTS sscs_api.user_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_id BIGINT NOT NULL REFERENCES sscs_api.users(id) ON DELETE CASCADE,
    target_user_id BIGINT NOT NULL REFERENCES sscs_api.users(id) ON DELETE CASCADE,
    message_id BIGINT REFERENCES sscs_api.messages(id) ON DELETE SET NULL,
    category VARCHAR(32) NOT NULL CHECK (category IN ('harassment', 'spam', 'inappropriate', 'impersonation', 'other')),
    details TEXT NOT NULL DEFAULT '' CHECK (LENGTH(details) <= 1000),
    status VARCHAR(16) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'resolved', 'dismissed')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    reviewed_by BIGINT REFERENCES sscs_api.users(id) ON DELETE SET NULL,
    reviewed_at TIMESTAMPTZ,
    CHECK (reporter_id <> target_user_id)
);

CREATE INDEX IF NOT EXISTS sscs_api_user_reports_queue_idx
    ON sscs_api.user_reports (status, created_at DESC);
